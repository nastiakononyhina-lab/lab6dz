#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <locale.h>

// Вариант 11: дано число N (N < 1000).
// Проверить, является ли произведение его цифр трёхзначным числом.
//
// Контрольные примеры:
// N = 999 -> 9*9*9 = 729 -> трёхзначное
// N = 123 -> 1*2*3 = 6   -> не трёхзначное
// N = 905 -> 9*0*5 = 0   -> не трёхзначное

int main()
{
    setlocale(LC_ALL, "Russian");

    int n, m;
    int p = 1;   // произведение цифр

    printf("Введите число N (от 1 до 999): ");
    scanf("%d", &n);

    if (n < 1 || n > 999)
    {
        printf("Число должно быть от 1 до 999\n");
        return 0;
    }

    m = n;
    while (m > 0)
    {
        p = p * (m % 10);   // берём последнюю цифру
        m = m / 10;         // отбрасываем её
    }

    printf("Произведение цифр: %d\n", p);

    if (p >= 100 && p <= 999)
        printf("Произведение трёхзначное\n");
    else
        printf("Произведение не трёхзначное\n");

    return 0;
}
